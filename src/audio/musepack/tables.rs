/// Combinatorial `C(n, k+1)` table (`Cnk[k][n]`), computed exactly (the
/// reference stores it as static data; the recurrence is equivalent).
pub fn cnk() -> [[u32; 32]; 16] {
    let mut table = [[0u32; 32]; 16];
    // Pascal's triangle in u64, then narrowed (max C(31,16) < 2^32).
    let mut pascal = [[0u64; 33]; 33];
    for n in 0..=32 {
        pascal[n][0] = 1;
        for k in 1..=n {
            pascal[n][k] = pascal[n - 1][k - 1] + pascal[n - 1].get(k).copied().unwrap_or(0);
        }
    }
    for k in 0..16 {
        for n in 0..32 {
            table[k][n] = pascal[n][k + 1] as u32;
        }
    }
    table
}

