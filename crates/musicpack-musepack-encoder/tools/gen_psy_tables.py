def parse_sections(path):
    """Return `name -> (count, [u32 bits])` and a scalars dict."""
    sections = {}
    scalars = {}
    with open(path) as fh:
        lines = [l.strip() for l in fh if l.strip()]
    i = 0
    while i < len(lines):
        parts = lines[i].split()
        name = parts[0]
        if name == "max_band":
            scalars[name] = int(parts[1])
            i += 1
        elif len(parts) == 2:
            n = int(parts[1])
            vals = [int(lines[i + 1 + j], 16) for j in range(n)]
            sections[name] = (n, vals)
            i += 1 + n
        else:
            raise SystemExit("bad line: " + lines[i])
    return sections, scalars


def emit_u32_array(out, name, vals, per_line=8, indent="    "):
    out.append(f"pub(crate) const {name}: [u32; {len(vals)}] = [\n")
    for i in range(0, len(vals), per_line):
        chunk = vals[i:i + per_line]
        out.append(indent + ", ".join(f"0x{v:08x}" for v in chunk) + ",\n")
    out.append("];\n\n")


def main():
    kernels, _ = parse_sections(f"{DATA}/kernels.txt")
    out = []
    out.append("//! Frozen psychoacoustic tables, generated by\n")
