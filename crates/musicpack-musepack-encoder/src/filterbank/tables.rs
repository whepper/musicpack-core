//! Authoritative analysis-filterbank tables.
//!
//! Two tables drive the filterbank:
//!
//! * [`CI_OPT`] — the 512-tap prototype window after `Klemm()`'s in-place
//!   transform. The reference builds it from an exact integer table divided by
//!   `2^21` (a power of two, so each value is exactly representable in `f32`)
//!   and then applies a deterministic integer reordering. That is reproduced
//!   here in [`build_ci_opt`] from [`CI_OPT_BASE`]; `ci_opt_bits.txt` in
//!   `tests/data/filterbank/` pins the result.
//! * [`MODULATION`] — the 32×32 modulation matrix `M`. The reference computes
//!   it with libm `cos`, which is not bit-portable across toolchains, so the
//!   authoritative bit patterns are **frozen** ([`MODULATION_BITS`]) rather
//!   than recomputed.
//!
//! Neither table relies on any global mutable state.

/// `2^21`, the prototype-window scale (the reference `0x200000`).
const PROTOTYPE_SCALE: f32 = 1.0 / 2_097_152.0;

/// Builds the post-`Klemm` prototype window from the base integers.
const fn build_ci_opt() -> [f32; 512] {
    // Step 1: `S` — scale the base, zero the middle eight, negate the top.
    let mut s = [0.0f32; 512];
    let mut i = 0;
    while i < 384 {
        s[i] = CI_OPT_BASE[i] as f32 * PROTOTYPE_SCALE;
        i += 1;
    }
    while i < 392 {
        s[i] = 0.0;
        i += 1;
    }
    while i < 512 {
        s[i] = -(CI_OPT_BASE[i] as f32 * PROTOTYPE_SCALE);
        i += 1;
    }

    // Step 2: the `FASTER` reorder.
    let mut out = [0.0f32; 512];
    i = 0;
    while i < 128 {
        out[i] = s[(i & 7) + 120 - (i & 120)];
        i += 1;
    }
    while i < 384 {
        out[i] = s[i];
        i += 1;
    }
    while i < 512 {
        out[i] = s[384 + (i & 7) + 120 - (i & 120)];
        i += 1;
    }
    out
}

/// The post-`Klemm` 512-tap prototype window.
pub const CI_OPT: [f32; 512] = build_ci_opt();

/// Builds the frozen modulation matrix.
const fn build_modulation() -> [f32; 1024] {
    let mut m = [0.0f32; 1024];
    let mut i = 0;
    while i < 1024 {
        m[i] = f32::from_bits(MODULATION_BITS[i]);
        i += 1;
    }
    m
}

/// The 32×32 modulation matrix (frozen authoritative bit patterns).
pub const MODULATION: [f32; 1024] = build_modulation();

